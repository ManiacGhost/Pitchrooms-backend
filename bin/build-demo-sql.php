<?php

declare(strict_types=1);

/**
 * Emits database/demo-users.sql — the demo accounts as plain SQL, so you can
 * import them through phpMyAdmin and sign in without shell access.
 *
 *   php bin/build-demo-sql.php
 *
 * Password hashes are generated fresh on each run, so the file never carries a
 * hash copied from somewhere else. Passwords: demo123 (admin123 for admin).
 *
 * This is test data. Do not import it into a database you intend to keep.
 */

use PitchRooms\Core\Autoloader;

$basePath = dirname(__DIR__);
require $basePath . '/src/Core/Autoloader.php';
Autoloader::register($basePath . '/src');

$users = [
    ['role' => 'agency',   'first' => 'Ava',     'last' => 'Shah',   'email' => 'agency@pitchrooms.demo',   'company' => 'Northstar Studio',  'title' => 'Creative Director', 'country' => 'India',                'panel' => 'agency-brand',      'profile' => 'agency'],
    ['role' => 'brand',    'first' => 'Noah',    'last' => 'Kapoor', 'email' => 'brand@pitchrooms.demo',    'company' => 'Aurora Retail',     'title' => 'Brand Lead',        'country' => 'United States',        'panel' => 'agency-brand',      'profile' => 'brand'],
    ['role' => 'employee', 'first' => 'Nishtha', 'last' => 'Patel',  'email' => 'employee@pitchrooms.demo', 'company' => '',                  'title' => 'Product Designer',  'country' => 'India',                'panel' => 'employee-employer', 'profile' => 'candidate'],
    ['role' => 'employer', 'first' => 'Liam',    'last' => 'Mehta',  'email' => 'employer@pitchrooms.demo', 'company' => 'Horizon Labs',      'title' => 'Head of Talent',    'country' => 'United Kingdom',       'panel' => 'employee-employer', 'profile' => 'employer'],
    ['role' => 'startup',  'first' => 'Zoe',     'last' => 'Rao',    'email' => 'startup@pitchrooms.demo',  'company' => 'Lumen Labs',        'title' => 'Founder',           'country' => 'Singapore',            'panel' => 'startup-investor',  'profile' => 'startup'],
    ['role' => 'investor', 'first' => 'Ethan',   'last' => 'Iyer',   'email' => 'investor@pitchrooms.demo', 'company' => 'Northwind Capital', 'title' => 'Partner',           'country' => 'United Arab Emirates', 'panel' => 'startup-investor',  'profile' => 'investor'],
    ['role' => 'admin',    'first' => 'Priya',   'last' => 'Nair',   'email' => 'admin@pitchrooms.demo',    'company' => 'PitchRooms',        'title' => 'Platform Admin',    'country' => 'India',                'panel' => 'internal',          'profile' => 'agency'],
];

$skills = [
    'agency'   => ['Branding', 'Campaign', 'Performance Marketing', 'Social'],
    'employee' => ['Product Design', 'Figma', 'UX Research', 'Design Systems'],
    'startup'  => ['SaaS', 'Analytics', 'B2B'],
];

function q(?string $value): string
{
    return $value === null ? 'NULL' : "'" . str_replace(["\\", "'"], ["\\\\", "''"], $value) . "'";
}

$lines = [];
$lines[] = '-- ===========================================================================';
$lines[] = '-- PitchRooms — demo accounts (TEST DATA)';
$lines[] = '-- Generated by bin/build-demo-sql.php on ' . gmdate('Y-m-d H:i:s') . ' UTC';
$lines[] = '--';
$lines[] = '-- Import after install.sql. Passwords: demo123, and admin123 for the admin.';
$lines[] = '-- Delete these accounts before the platform goes live.';
$lines[] = '-- ===========================================================================';
$lines[] = '';
$lines[] = 'SET NAMES utf8mb4;';
$lines[] = '';

foreach ($users as $user) {
    $id = $user['role'] . '-demo-' . substr(sha1($user['email']), 0, 10);
    $name = $user['role'] === 'brand' ? $user['company'] : trim($user['first'] . ' ' . $user['last']);
    $hash = password_hash($user['role'] === 'admin' ? 'admin123' : 'demo123', PASSWORD_BCRYPT, ['cost' => 11]);

    $lines[] = sprintf(
        "INSERT INTO users (id, panel_id, role, first_name, last_name, name, email, password_hash,\n"
        . "                   phone, country, company, title, email_verified_at, phone_verified_at,\n"
        . "                   verification_status, account_status, created_at, updated_at)\n"
        . "VALUES (%s, %s, %s, %s, %s, %s, %s, %s,\n"
        . "        '+91 98765 43210', %s, %s, %s, UTC_TIMESTAMP(), UTC_TIMESTAMP(),\n"
        . "        'Verified', 'Active', UTC_TIMESTAMP(), UTC_TIMESTAMP())\n"
        . "ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), name = VALUES(name);",
        q($id),
        q($user['panel']),
        q($user['role']),
        q($user['first']),
        q($user['last'] ?: null),
        q($name),
        q($user['email']),
        q($hash),
        q($user['country']),
        q($user['company'] ?: null),
        q($user['title'])
    );
    $lines[] = '';

    $payload = json_encode($user['role'] === 'startup'
        ? ['founder' => $user['first'] . ' ' . $user['last'], 'tags' => ['SaaS']]
        : ($user['role'] === 'investor' ? ['firm' => $user['company'], 'investorType' => 'VC firm'] : []));

    $lines[] = sprintf(
        "INSERT INTO profiles (user_id, type, display_name, headline, bio, location, sector, stage,\n"
        . "                      experience, rating, reviews, trust_score, verified, payload, created_at, updated_at)\n"
        . "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, 'Senior', 0, 0, 0, 1, %s, UTC_TIMESTAMP(), UTC_TIMESTAMP())\n"
        . "ON DUPLICATE KEY UPDATE display_name = VALUES(display_name), verified = 1;",
        q($id),
        q($user['profile']),
        q($user['company'] ?: $name),
        q($user['title']),
        q($name . ' on PitchRooms.'),
        q($user['country']),
        q(in_array($user['role'], ['startup', 'investor'], true) ? 'SaaS' : null),
        q($user['role'] === 'startup' ? 'Seed' : null),
        q($payload ?: '{}')
    );
    $lines[] = '';

    foreach ($skills[$user['role']] ?? [] as $skill) {
        $lines[] = sprintf(
            'INSERT IGNORE INTO profile_skills (user_id, skill) VALUES (%s, %s);',
            q($id),
            q($skill)
        );
    }
    $lines[] = '';
}

$target = $basePath . '/database/demo-users.sql';
file_put_contents($target, implode("\n", $lines));

printf("Wrote database/demo-users.sql (%d accounts, %s)\n", count($users), number_format(filesize($target) / 1024, 1) . ' KB');
echo "Passwords: demo123 — admin123 for admin@pitchrooms.demo\n";
