<?php

declare(strict_types=1);

/**
 * Concatenates every migration into database/install.sql — one file you can
 * import through phpMyAdmin when the host gives you no SSH access.
 *
 *   php bin/build-installer.php
 *
 * The output records itself in the `migrations` table, so a later
 * `php bin/migrate.php` over SSH sees the schema as already applied and does
 * not try to re-create it.
 */

$basePath = dirname(__DIR__);
$files = glob($basePath . '/database/migrations/*.sql') ?: [];
sort($files);

if ($files === []) {
    fwrite(STDERR, "No migrations found.\n");
    exit(1);
}

$out = [];
$out[] = '-- ===========================================================================';
$out[] = '-- PitchRooms — full schema installer';
$out[] = '-- Generated by bin/build-installer.php on ' . gmdate('Y-m-d H:i:s') . ' UTC';
$out[] = '--';
$out[] = '-- phpMyAdmin: select your database, open Import, choose this file, Go.';
$out[] = '-- Safe to re-run: every statement is CREATE TABLE IF NOT EXISTS or an';
$out[] = '-- INSERT ... ON DUPLICATE KEY UPDATE.';
$out[] = '-- ===========================================================================';
$out[] = '';
$out[] = 'SET NAMES utf8mb4;';
$out[] = 'SET time_zone = "+00:00";';
$out[] = 'SET FOREIGN_KEY_CHECKS = 1;';
$out[] = '';
$out[] = 'CREATE TABLE IF NOT EXISTS migrations (';
$out[] = '    id INT AUTO_INCREMENT PRIMARY KEY,';
$out[] = '    filename VARCHAR(190) NOT NULL UNIQUE,';
$out[] = '    applied_at DATETIME NOT NULL';
$out[] = ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;';
$out[] = '';

foreach ($files as $file) {
    $name = basename($file);
    $sql = trim((string) file_get_contents($file));

    $out[] = '-- ---------------------------------------------------------------------------';
    $out[] = '-- ' . $name;
    $out[] = '-- ---------------------------------------------------------------------------';
    $out[] = '';
    $out[] = $sql;
    $out[] = '';
    $out[] = sprintf(
        "INSERT INTO migrations (filename, applied_at) VALUES ('%s', UTC_TIMESTAMP())\n    ON DUPLICATE KEY UPDATE applied_at = applied_at;",
        addslashes($name)
    );
    $out[] = '';
}

$target = $basePath . '/database/install.sql';
file_put_contents($target, implode("\n", $out));

printf(
    "Wrote %s (%d migrations, %s)\n",
    'database/install.sql',
    count($files),
    number_format(filesize($target) / 1024, 1) . ' KB'
);
